import java.lang.reflect.*;
import java.text.BreakIterator;
import java.util.*;

/** Build-only reference data for SQL normalization; JDK21 Locale.ROOT is the contract.
 * Run with --add-opens java.base/sun.text=ALL-UNNAMED --add-opens java.base/java.lang=ALL-UNNAMED.
 * Emits nonsecret Unicode properties and the JDK's word-break DFA, never application data. */
public class GenerateUnicode {
    public static void main(String[] args) throws Exception {
        if (Runtime.version().feature() != 21) throw new IllegalStateException("JDK21 required");
        Object words = BreakIterator.getWordInstance(Locale.ROOT);
        Class<?> type = words.getClass();
        Method category = type.getDeclaredMethod("lookupCategory", int.class); category.setAccessible(true);
        Method cased = Class.forName("java.lang.ConditionalSpecialCasing").getDeclaredMethod("isCased", int.class); cased.setAccessible(true);
        Field statesField = type.getDeclaredField("stateTable"); statesField.setAccessible(true);
        Field endsField = type.getDeclaredField("endStates"); endsField.setAccessible(true);
        Field aheadField = type.getDeclaredField("lookaheadStates"); aheadField.setAccessible(true);
        short[] states = (short[]) statesField.get(words);
        boolean[] ends = (boolean[]) endsField.get(words), ahead = (boolean[]) aheadField.get(words);
        int columns = states.length / ends.length;
        for(int state=0;state<ends.length;state++) System.out.println("INSERT dbo.AiDataWordTransition VALUES(-1,"+state+","+state+","+(ends[state]?1:0)+","+(ahead[state]?1:0)+");");
        System.out.println("-- Generated by JDK " + Runtime.version() + ", Locale.ROOT; regenerate and run executable parity on change.");
        int start = 0; String previous = null;
        for (int cp = 0; cp <= 0x110000; cp++) {
            String flags = cp == 0x110000 ? null : category.invoke(words, cp) + "," + (Character.isWhitespace(cp) ? 1 : 0) + "," + (Character.isLetterOrDigit(cp) ? 1 : 0) + "," + ((boolean)cased.invoke(null, cp) ? 1 : 0);
            if (!Objects.equals(flags, previous)) {
                if (previous != null) System.out.println("INSERT dbo.AiDataUnicodeRange VALUES(" + start + "," + (cp-1) + "," + previous + ");");
                start = cp; previous = flags;
            }
            if (cp <= 0x10ffff && (cp < 0xd800 || cp > 0xdfff)) {
                String original = new String(Character.toChars(cp)), lower = original.toLowerCase(Locale.ROOT);
                if (!original.equals(lower)) System.out.println("INSERT dbo.AiDataUnicodeLower VALUES(" + cp + ",CONVERT(nvarchar(4),0x" + HexFormat.of().formatHex(lower.getBytes(java.nio.charset.StandardCharsets.UTF_16LE)) + "));");
            }
        }
        for (int state = 0; state < ends.length; state++) for (int cat = 0; cat < columns; cat++) {
            int next = states[state*columns+cat];
            System.out.println("INSERT dbo.AiDataWordTransition VALUES(" + state + "," + cat + "," + next + "," + (ends[next]?1:0) + "," + (ahead[next]?1:0) + ");");
        }
    }
}
