#!/usr/bin/env python3
"""Generate the reviewable Shale test ownership and full-suite-only inventory."""

from __future__ import annotations

import argparse
import fnmatch
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
OUTPUT = ROOT / "docs" / "testing" / "full-suite-only-inventory.md"


def test_sources() -> list[Path]:
    return sorted(ROOT.glob("shale-*/src/test/java/**/*Test.java"))


def critical_names() -> set[str]:
    names = set()
    for line in (HERE / "critical-tests.txt").read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.lstrip().startswith("#"):
            names.add(Path(line.strip()).stem)
    return names


def invocation_count(path: Path) -> int:
    return len(re.findall(r"@(Test|ParameterizedTest|RepeatedTest|TestFactory)\b", path.read_text(encoding="utf-8")))


def owners(name: str, config: dict) -> list[str]:
    return sorted(area for area, definition in config["areas"].items()
                  if any(fnmatch.fnmatchcase(name, pattern) for pattern in definition.get("test_patterns", [])))


def priority(name: str) -> str:
    lowered = name.lower()
    if "phase" in lowered or re.search(r"step\d|step_\d", lowered):
        return "phase-numbered historical contract"
    if any(word in lowered for word in ("layout", "visual", "render", "geometry", "contentsizing", "tooltip")):
        return "brittle rendered UI geometry"
    if any(word in lowered for word in ("source", "migration", "contract")):
        return "duplicate source-contract coverage"
    if any(word in lowered for word in ("obsolete", "legacy", "compatibility", "inventory")):
        return "likely obsolete"
    return "still valuable but feature-specific"


def render() -> str:
    config = json.loads((HERE / "test-areas.json").read_text(encoding="utf-8"))
    critical = critical_names()
    rows = []
    total_invocations = critical_invocations = 0
    full_only = []
    for path in test_sources():
        name = path.stem
        count = invocation_count(path)
        total_invocations += count
        is_critical = name in critical
        if is_critical:
            critical_invocations += count
        area_owners = owners(name, config)
        relative = path.relative_to(ROOT).as_posix()
        rows.append((relative, is_critical, area_owners, count))
        if not is_critical and not area_owners:
            full_only.append((priority(name), relative, count))

    lines = [
        "# Full-suite-only test review inventory", "",
        "Generated by `python build/test-selection/inventory.py --write`. Do not edit by hand.", "",
        "Every Surefire-discoverable class is reachable through `mvn -Pall-tests test`. Critical tests are",
        "also reachable through `mvn test`; feature-owned tests are reachable through the selector. Rows below",
        "are intentionally full-suite-only until reviewed, consolidated, or assigned to an affected area.", "",
        "## Inventory summary", "",
        f"- Discoverable test classes: **{len(rows)}**",
        f"- Source-declared JUnit test methods/factories: **{total_invocations}** (parameterized runtime invocations may be higher)",
        f"- Critical classes: **{len(critical)}**",
        f"- Critical source-declared methods/factories: **{critical_invocations}** ({critical_invocations / total_invocations:.1%})",
        f"- Full-suite-only classes: **{len(full_only)}**", "",
        "## Prioritized full-suite-only review", "",
        "This is a review queue, not a deletion decision. The category is a name-based triage heuristic.", "",
        "| Priority | Test source | Declared tests |", "| --- | --- | ---: |",
    ]
    for category, path, count in sorted(full_only):
        lines.append(f"| {category} | `{path}` | {count} |")
    lines.extend(["", "## Complete ownership manifest", "", "| Test source | Critical | Feature areas | Declared tests |", "| --- | :---: | --- | ---: |"])
    for path, is_critical, area_owners, count in rows:
        lines.append(f"| `{path}` | {'yes' if is_critical else 'no'} | {', '.join(area_owners) or 'full-suite-only'} | {count} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != content:
            print(f"Stale inventory: run {Path(__file__).relative_to(ROOT)} --write")
            return 1
        print("Test inventory is current.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
